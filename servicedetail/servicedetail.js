/* =========================================================
   GET SERVICE FROM URL
========================================================= */

function getSelectedService() {
  const params = new URLSearchParams(window.location.search);

  return params.get("service") || "kitchen";
}

/* =========================================================
   UPDATE SERVICE DETAIL PAGE
========================================================= */

function loadService(serviceKey) {
  const service = serviceData[serviceKey];

  if (!service) {
    console.warn("Service not found:", serviceKey);
    return;
  }

  /* =======================================================
     HERO
  ======================================================= */

  document.getElementById("serviceDetailTag").textContent = service.tag;

  document.getElementById("serviceDetailTitle").childNodes[0].textContent =
    service.title + " ";

  document.querySelector("#serviceDetailTitle span").textContent =
    service.titleSpan;

  document.getElementById("serviceDetailDescription").textContent =
    service.description;

  /* =======================================================
     OVERVIEW
  ======================================================= */

  document.getElementById("serviceDetailOverviewImage").src =
    service.overviewImage;

  document.getElementById("serviceDetailOverviewImage").alt =
    service.overviewImageAlt;

  document.getElementById("serviceDetailOverviewTag").textContent =
    service.overviewTag;

  document.getElementById(
    "serviceDetailOverviewTitle",
  ).childNodes[0].textContent = service.overviewTitle + " ";

  document.querySelector("#serviceDetailOverviewTitle span").textContent =
    service.overviewTitleSpan;

  document.getElementById("serviceDetailOverviewDescription").textContent =
    service.overviewDescription;

  service.overviewPoints.forEach((point, index) => {
    const number = index + 1;

    document.getElementById(
      `serviceDetailOverviewPoint${number}Title`,
    ).textContent = point.title;

    document.getElementById(
      `serviceDetailOverviewPoint${number}Text`,
    ).textContent = point.text;
  });

  /* =======================================================
     HOW IT WORKS
  ======================================================= */

  document.getElementById("serviceDetailProcessTag").textContent =
    service.processTag;

  document.getElementById(
    "serviceDetailProcessTitle",
  ).childNodes[0].textContent = service.processTitle + " ";

  document.querySelector("#serviceDetailProcessTitle span").textContent =
    service.processTitleSpan;

  document.getElementById("serviceDetailProcessDescription").textContent =
    service.processDescription;

  service.process.forEach((step, index) => {
    const number = index + 1;

    document
      .getElementById(`serviceDetailProcessIcon${number}`)
      .setAttribute("data-lucide", step.icon);

    document.getElementById(
      `serviceDetailProcessStep${number}Title`,
    ).textContent = step.title;

    document.getElementById(
      `serviceDetailProcessStep${number}Text`,
    ).textContent = step.text;
  });

  /* =======================================================
     KEY BENEFITS
  ======================================================= */

  document.getElementById("serviceDetailBenefitsTag").textContent =
    service.benefitsTag;

  document.getElementById(
    "serviceDetailBenefitsTitle",
  ).childNodes[0].textContent = service.benefitsTitle + " ";

  document.querySelector("#serviceDetailBenefitsTitle span").textContent =
    service.benefitsTitleSpan;

  document.getElementById("serviceDetailBenefitsDescription").textContent =
    service.benefitsDescription;

  service.benefits.forEach((benefit, index) => {
    const number = index + 1;

    document
      .getElementById(`serviceDetailBenefitIcon${number}`)
      .setAttribute("data-lucide", benefit.icon);

    document.getElementById(`serviceDetailBenefitTitle${number}`).textContent =
      benefit.title;

    document.getElementById(`serviceDetailBenefitText${number}`).textContent =
      benefit.text;
  });

  /* =======================================================
     REFRESH LUCIDE ICONS
  ======================================================= */

  if (window.lucide) {
    lucide.createIcons();
  }
}

/* =========================================================
   PAGE LOAD
========================================================= */

document.addEventListener("DOMContentLoaded", () => {
  const selectedService = getSelectedService();

  loadService(selectedService);
});
